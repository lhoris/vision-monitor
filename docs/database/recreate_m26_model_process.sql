-- TB_M26_MODEL_PROCESS recreation
--
-- WARNING:
-- 1. Confirm the backup row count before running this script.
-- 2. MySQL/MariaDB DDL statements implicitly commit transactions.
-- 3. This script drops only TB_M26_MODEL_PROCESS. Event and command tables
--    are preserved and continue to use MODEL_PROCESS_ID logically.
-- 4. Restore is intentionally explicit so newly added Agent columns do not
--    receive accidental values from the old table layout.

DROP TABLE IF EXISTS TB_M26_MODEL_PROCESS;

CREATE TABLE TB_M26_MODEL_PROCESS (
    -- Audit columns must remain first.
    CREATED_OBJECT_TYPE VARCHAR(1) DEFAULT NULL COMMENT '생성 객체 유형',
    CREATED_OBJECT_ID VARCHAR(22) DEFAULT NULL COMMENT '생성 객체 식별자',
    CREATED_PROGRAM_ID VARCHAR(22) DEFAULT NULL COMMENT '생성 프로그램 식별자',
    CREATED_TIMESTAMP DATETIME DEFAULT CURRENT_TIMESTAMP() COMMENT '생성 일시',
    LAST_UPDATED_OBJECT_TYPE VARCHAR(1) DEFAULT NULL COMMENT '최종 수정 객체 유형',
    LAST_UPDATED_OBJECT_ID VARCHAR(22) DEFAULT NULL COMMENT '최종 수정 객체 식별자',
    LAST_UPDATED_PROGRAM_ID VARCHAR(22) DEFAULT NULL COMMENT '최종 수정 프로그램 식별자',
    LAST_UPDATED_TIMESTAMP DATETIME DEFAULT CURRENT_TIMESTAMP() ON UPDATE CURRENT_TIMESTAMP() COMMENT '최종 수정 일시',
    DATA_END_STATUS VARCHAR(1) DEFAULT 'N' COMMENT '데이터 종료 상태',
    DATA_END_OBJECT_TYPE VARCHAR(1) DEFAULT NULL COMMENT '데이터 종료 객체 유형',
    DATA_END_OBJECT_ID VARCHAR(22) DEFAULT NULL COMMENT '데이터 종료 객체 식별자',
    DATA_END_PROGRAM_ID VARCHAR(22) DEFAULT NULL COMMENT '데이터 종료 프로그램 식별자',
    DATA_END_TIMESTAMP DATETIME DEFAULT NULL COMMENT '데이터 종료 일시',

    -- Identity and operational lookup columns come before attributes.
    MODEL_PROCESS_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '모델 프로세스 식별자',
    AGENT_ID VARCHAR(64) DEFAULT NULL COMMENT '모델 프로세스를 담당하는 Agent 식별자',
    SERVER_IP VARCHAR(45) NOT NULL COMMENT '모델 프로세스 실행 서버 IP 주소',
    PROCESS_PID INT DEFAULT NULL COMMENT '최근 운영체제 프로세스 ID',

    -- Business and runtime attributes.
    MODEL_NAME VARCHAR(200) NOT NULL COMMENT 'AI 모델명',
    AUTOMATION_NAME VARCHAR(200) NOT NULL COMMENT '조업 자동화 기술명',
    PYTHON_PROJECT_PATH VARCHAR(1000) NOT NULL COMMENT 'Python 프로젝트 루트 경로',
    PROCESS_AREA_CODE VARCHAR(30) NOT NULL COMMENT '공정 코드',
    PROCESS_STATUS VARCHAR(20) NOT NULL DEFAULT 'UNKNOWN' COMMENT 'Python 프로세스 생명주기 상태',
    MONITORING_STATUS VARCHAR(20) NOT NULL DEFAULT 'UNKNOWN' COMMENT 'Agent 모니터링 상태',
    CONTROL_STATUS VARCHAR(20) NOT NULL DEFAULT 'UNKNOWN' COMMENT '제어 연동 상태',
    LAST_STATUS_TIMESTAMP DATETIME DEFAULT NULL COMMENT '최근 프로세스 상태 갱신 일시',
    DESCRIPTION VARCHAR(1000) DEFAULT NULL COMMENT '프로세스 설명',
    AUTO_RESTART BOOLEAN DEFAULT TRUE COMMENT '자동 재시작 사용 여부',
    MAX_RESTART_ATTEMPTS INT DEFAULT 3 COMMENT '자동 재시작 최대 시도 횟수',
    RESTART_DELAY_SEC INT DEFAULT 10 COMMENT '자동 재시작 전 대기 시간(초)',
    TIMEOUT_SEC INT DEFAULT 3600 COMMENT '프로세스 제어 명령 제한 시간(초)',
    HEALTH_CHECK_ENABLED BOOLEAN DEFAULT TRUE COMMENT '헬스체크 사용 여부',
    HEALTH_CHECK_INTERVAL_SEC INT DEFAULT 30 COMMENT '헬스체크 주기(초)',
    HEALTH_CHECK_ENDPOINT VARCHAR(512) DEFAULT NULL COMMENT '헬스체크 엔드포인트',
    LAST_HEALTH_CHECK DATETIME DEFAULT NULL COMMENT '최근 헬스체크 일시',
    LAST_HEARTBEAT DATETIME DEFAULT NULL COMMENT '최근 Agent 하트비트 일시',
    HEALTH_STATUS VARCHAR(32) DEFAULT NULL COMMENT '최근 헬스체크 결과',
    UPTIME_SEC BIGINT DEFAULT NULL COMMENT '확인된 프로세스 가동 시간(초)',
    ERROR_MESSAGE LONGTEXT DEFAULT NULL COMMENT '최근 프로세스 또는 헬스체크 오류 메시지',

    PRIMARY KEY (MODEL_PROCESS_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='AI 모델 프로세스 정의 및 실행 상태';

INSERT INTO TB_M26_MODEL_PROCESS (
    CREATED_OBJECT_TYPE, CREATED_OBJECT_ID, CREATED_PROGRAM_ID, CREATED_TIMESTAMP,
    LAST_UPDATED_OBJECT_TYPE, LAST_UPDATED_OBJECT_ID, LAST_UPDATED_PROGRAM_ID, LAST_UPDATED_TIMESTAMP,
    DATA_END_STATUS, DATA_END_OBJECT_TYPE, DATA_END_OBJECT_ID, DATA_END_PROGRAM_ID, DATA_END_TIMESTAMP,
    MODEL_PROCESS_ID, PROCESS_AREA_CODE, MODEL_NAME, AUTOMATION_NAME, SERVER_IP,
    PYTHON_PROJECT_PATH, PROCESS_STATUS, MONITORING_STATUS, CONTROL_STATUS,
    LAST_STATUS_TIMESTAMP, DESCRIPTION
)
SELECT
    CREATED_OBJECT_TYPE, CREATED_OBJECT_ID, CREATED_PROGRAM_ID, CREATED_TIMESTAMP,
    LAST_UPDATED_OBJECT_TYPE, LAST_UPDATED_OBJECT_ID, LAST_UPDATED_PROGRAM_ID, LAST_UPDATED_TIMESTAMP,
    DATA_END_STATUS, DATA_END_OBJECT_TYPE, DATA_END_OBJECT_ID, DATA_END_PROGRAM_ID, DATA_END_TIMESTAMP,
    MODEL_PROCESS_ID, PROCESS_AREA_CODE, MODEL_NAME, AUTOMATION_NAME, SERVER_IP,
    PYTHON_PROJECT_PATH, PROCESS_STATUS, MONITORING_STATUS, CONTROL_STATUS,
    LAST_STATUS_TIMESTAMP, DESCRIPTION
FROM TB_M26_MODEL_PROCESS_BACKUP_20261012;

