-- TB_M26_MODEL_PROCESS recreation
--
-- WARNING:
-- 1. Confirm the backup row count before running this script.
-- 2. MySQL/MariaDB DDL statements implicitly commit transactions.
-- 3. This script drops only TB_M26_MODEL_PROCESS. Event and command tables
--    are preserved and continue to use MODEL_PROCESS_ID logically.
-- 4. Restore is intentionally explicit so newly added Agent columns do not
--    receive accidental values from the old table layout.

DROP TABLE IF EXISTS TB_M26_MODEL_PROCESS;

CREATE TABLE TB_M26_MODEL_PROCESS (
    -- Audit columns must remain first.
    CREATED_OBJECT_TYPE VARCHAR(1) DEFAULT NULL,
    CREATED_OBJECT_ID VARCHAR(22) DEFAULT NULL,
    CREATED_PROGRAM_ID VARCHAR(22) DEFAULT NULL,
    CREATED_TIMESTAMP DATETIME DEFAULT CURRENT_TIMESTAMP(),
    LAST_UPDATED_OBJECT_TYPE VARCHAR(1) DEFAULT NULL,
    LAST_UPDATED_OBJECT_ID VARCHAR(22) DEFAULT NULL,
    LAST_UPDATED_PROGRAM_ID VARCHAR(22) DEFAULT NULL,
    LAST_UPDATED_TIMESTAMP DATETIME DEFAULT CURRENT_TIMESTAMP() ON UPDATE CURRENT_TIMESTAMP(),
    DATA_END_STATUS VARCHAR(1) DEFAULT 'N',
    DATA_END_OBJECT_TYPE VARCHAR(1) DEFAULT NULL,
    DATA_END_OBJECT_ID VARCHAR(22) DEFAULT NULL,
    DATA_END_PROGRAM_ID VARCHAR(22) DEFAULT NULL,
    DATA_END_TIMESTAMP DATETIME DEFAULT NULL,

    -- Identity and operational lookup columns come before attributes.
    MODEL_PROCESS_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    AGENT_ID VARCHAR(64) DEFAULT NULL,
    SERVER_IP VARCHAR(45) NOT NULL,
    PROCESS_PID INT DEFAULT NULL,

    -- Business and runtime attributes.
    MODEL_NAME VARCHAR(200) NOT NULL,
    AUTOMATION_NAME VARCHAR(200) NOT NULL,
    PYTHON_PROJECT_PATH VARCHAR(1000) NOT NULL,
    PROCESS_AREA_CODE VARCHAR(30) NOT NULL,
    PROCESS_STATUS VARCHAR(20) NOT NULL DEFAULT 'UNKNOWN',
    MONITORING_STATUS VARCHAR(20) NOT NULL DEFAULT 'UNKNOWN',
    CONTROL_STATUS VARCHAR(20) NOT NULL DEFAULT 'UNKNOWN',
    LAST_STATUS_TIMESTAMP DATETIME DEFAULT NULL,
    DESCRIPTION VARCHAR(1000) DEFAULT NULL,
    AUTO_RESTART BOOLEAN DEFAULT TRUE,
    MAX_RESTART_ATTEMPTS INT DEFAULT 3,
    RESTART_DELAY_SEC INT DEFAULT 10,
    TIMEOUT_SEC INT DEFAULT 3600,
    HEALTH_CHECK_ENABLED BOOLEAN DEFAULT TRUE,
    HEALTH_CHECK_INTERVAL_SEC INT DEFAULT 30,
    HEALTH_CHECK_ENDPOINT VARCHAR(512) DEFAULT NULL,
    LAST_HEALTH_CHECK DATETIME DEFAULT NULL,
    LAST_HEARTBEAT DATETIME DEFAULT NULL,
    HEALTH_STATUS VARCHAR(32) DEFAULT NULL,
    UPTIME_SEC BIGINT DEFAULT NULL,
    ERROR_MESSAGE LONGTEXT DEFAULT NULL,

    PRIMARY KEY (MODEL_PROCESS_ID),
    KEY IX_M26_MODEL_PROCESS_AREA (PROCESS_AREA_CODE, DATA_END_STATUS),
    KEY IX_M26_MODEL_PROCESS_STATUS (MONITORING_STATUS, CONTROL_STATUS, DATA_END_STATUS)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

INSERT INTO TB_M26_MODEL_PROCESS (
    CREATED_OBJECT_TYPE, CREATED_OBJECT_ID, CREATED_PROGRAM_ID, CREATED_TIMESTAMP,
    LAST_UPDATED_OBJECT_TYPE, LAST_UPDATED_OBJECT_ID, LAST_UPDATED_PROGRAM_ID, LAST_UPDATED_TIMESTAMP,
    DATA_END_STATUS, DATA_END_OBJECT_TYPE, DATA_END_OBJECT_ID, DATA_END_PROGRAM_ID, DATA_END_TIMESTAMP,
    MODEL_PROCESS_ID, PROCESS_AREA_CODE, MODEL_NAME, AUTOMATION_NAME, SERVER_IP,
    PYTHON_PROJECT_PATH, PROCESS_STATUS, MONITORING_STATUS, CONTROL_STATUS,
    LAST_STATUS_TIMESTAMP, DESCRIPTION
)
SELECT
    CREATED_OBJECT_TYPE, CREATED_OBJECT_ID, CREATED_PROGRAM_ID, CREATED_TIMESTAMP,
    LAST_UPDATED_OBJECT_TYPE, LAST_UPDATED_OBJECT_ID, LAST_UPDATED_PROGRAM_ID, LAST_UPDATED_TIMESTAMP,
    DATA_END_STATUS, DATA_END_OBJECT_TYPE, DATA_END_OBJECT_ID, DATA_END_PROGRAM_ID, DATA_END_TIMESTAMP,
    MODEL_PROCESS_ID, PROCESS_AREA_CODE, MODEL_NAME, AUTOMATION_NAME, SERVER_IP,
    PYTHON_PROJECT_PATH, PROCESS_STATUS, MONITORING_STATUS, CONTROL_STATUS,
    LAST_STATUS_TIMESTAMP, DESCRIPTION
FROM TB_M26_MODEL_PROCESS_BACKUP_20261012;

-- Verification
SELECT 'RESTORED' AS TABLE_NAME, COUNT(*) AS ROW_COUNT
FROM TB_M26_MODEL_PROCESS
UNION ALL
SELECT 'BACKUP' AS TABLE_NAME, COUNT(*) AS ROW_COUNT
FROM TB_M26_MODEL_PROCESS_BACKUP_20261012;
