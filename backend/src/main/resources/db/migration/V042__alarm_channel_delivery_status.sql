ALTER TABLE TB_M26_ALARM_LOG
    ADD COLUMN SOURCE_EVENT_ID VARCHAR(100) DEFAULT NULL COMMENT '발생 주체의 고유 이벤트 ID',
    ADD COLUMN APP_STATUS VARCHAR(20) NOT NULL DEFAULT 'PENDING' COMMENT '앱 알람 전송 상태',
    ADD COLUMN EMAIL_STATUS VARCHAR(20) NOT NULL DEFAULT 'SKIPPED' COMMENT '메일 전송 상태',
    ADD COLUMN TEAMS_STATUS VARCHAR(20) NOT NULL DEFAULT 'SKIPPED' COMMENT '팀즈 알림봇 전송 상태';

UPDATE TB_M26_ALARM_LOG
SET APP_STATUS = 'SENT'
WHERE APP_STATUS = 'PENDING';

ALTER TABLE TB_M26_ALARM_LOG
    ADD UNIQUE KEY UK_M26_ALARM_LOG_SOURCE_TARGET (SOURCE_EVENT_ID, TARGET_USER_ID);

ALTER TABLE TB_M26_ALARM_RULE
    DROP COLUMN IF EXISTS SAVE_STATUS,
    DROP COLUMN IF EXISTS RECEIVE_STATUS,
    DROP COLUMN IF EXISTS PUSH_STATUS,
    DROP COLUMN IF EXISTS EMAIL_STATUS,
    DROP COLUMN IF EXISTS TEAMS_STATUS,
    DROP COLUMN IF EXISTS RECIPIENT_SCOPE;

ALTER TABLE TB_M26_USER_ALERT_PREF
    DROP INDEX IF EXISTS UK_M26_USER_ALERT_PREF_USER,
    ADD UNIQUE KEY UK_M26_USER_ALERT_PREF_TYPE (USER_ID, ALARM_TYPE_CODE);
