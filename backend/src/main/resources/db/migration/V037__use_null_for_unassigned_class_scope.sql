UPDATE TB_M26_USER
SET CLASS_CODE = NULL
WHERE CLASS_CODE = 'COMMON';

UPDATE TB_M26_VIDEO_SOURCE
SET CLASS_CODE = NULL
WHERE CLASS_CODE = 'COMMON';

ALTER TABLE TB_M26_USER
    MODIFY COLUMN CLASS_CODE VARCHAR(30) NULL DEFAULT NULL;

ALTER TABLE TB_M26_VIDEO_SOURCE
    MODIFY COLUMN CLASS_CODE VARCHAR(30) NULL DEFAULT NULL;

DELETE detail
FROM TB_M26_CODE_DETAIL detail
JOIN TB_M26_CODE code ON code.CODE_ID = detail.CODE_ID
WHERE UPPER(code.CODE_NAME) = 'USER_CLASS'
  AND UPPER(detail.CODE_VALUE) = 'COMMON';
