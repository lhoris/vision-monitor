CREATE TABLE IF NOT EXISTS TB_M26_ALARM_RULE (
    CREATED_OBJECT_TYPE VARCHAR(1) DEFAULT NULL COMMENT '생성Object유형',
    CREATED_OBJECT_ID VARCHAR(22) DEFAULT NULL COMMENT '생성ObjectID',
    CREATED_PROGRAM_ID VARCHAR(22) DEFAULT NULL COMMENT '생성프로그램ID',
    CREATED_TIMESTAMP DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '생성일시',
    LAST_UPDATED_OBJECT_TYPE VARCHAR(1) DEFAULT NULL COMMENT '최종변경Object유형',
    LAST_UPDATED_OBJECT_ID VARCHAR(22) DEFAULT NULL COMMENT '최종변경ObjectID',
    LAST_UPDATED_PROGRAM_ID VARCHAR(22) DEFAULT NULL COMMENT '최종변경프로그램ID',
    LAST_UPDATED_TIMESTAMP DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '최종변경일시',
    DATA_END_STATUS VARCHAR(1) DEFAULT 'N' COMMENT '데이터종료여부',
    DATA_END_OBJECT_TYPE VARCHAR(1) DEFAULT NULL COMMENT '데이터종료Object유형',
    DATA_END_OBJECT_ID VARCHAR(22) DEFAULT NULL COMMENT '데이터종료ObjectID',
    DATA_END_PROGRAM_ID VARCHAR(22) DEFAULT NULL COMMENT '데이터종료프로그램ID',
    DATA_END_TIMESTAMP DATETIME DEFAULT NULL COMMENT '데이터종료일시',
    ALARM_RULE_ID BIGINT NOT NULL AUTO_INCREMENT COMMENT '알람 규칙 ID',
    ALARM_CODE VARCHAR(50) NOT NULL COMMENT '알람 코드',
    ALARM_NAME VARCHAR(100) NOT NULL COMMENT '알람 명칭',
    ALARM_NAME_KO VARCHAR(100) DEFAULT NULL COMMENT '알람 한글 명칭',
    ALARM_NAME_EN VARCHAR(100) DEFAULT NULL COMMENT '알람 영문 명칭',
    ALARM_DESCRIPTION VARCHAR(1000) DEFAULT NULL COMMENT '알람 설명',
    ALARM_CATEGORY VARCHAR(20) NOT NULL DEFAULT 'GENERAL' COMMENT '알람 대분류',
    RECIPIENT_SCOPE VARCHAR(20) NOT NULL DEFAULT 'ALL_ADMIN' COMMENT '수신자 범위',
    ACKNOWLEDGEMENT_SCOPE VARCHAR(20) NOT NULL DEFAULT 'INDIVIDUAL' COMMENT '알람 확인 범위',
    SAVE_STATUS VARCHAR(1) NOT NULL DEFAULT 'Y' COMMENT '로그 저장 여부',
    RECEIVE_STATUS VARCHAR(1) NOT NULL DEFAULT 'Y' COMMENT '기본 수신 여부',
    PUSH_STATUS VARCHAR(1) NOT NULL DEFAULT 'Y' COMMENT '기본 Push 수신 여부',
    EMAIL_STATUS VARCHAR(1) NOT NULL DEFAULT 'N' COMMENT '기본 메일 수신 여부',
    TEAMS_STATUS VARCHAR(1) NOT NULL DEFAULT 'N' COMMENT '기본 Teams 수신 여부',
    PRIMARY KEY (ALARM_RULE_ID),
    UNIQUE KEY UK_M26_ALARM_RULE_CODE (ALARM_CODE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='알람 규칙';

INSERT INTO TB_M26_ALARM_RULE (
    CREATED_OBJECT_TYPE, CREATED_OBJECT_ID, CREATED_PROGRAM_ID,
    LAST_UPDATED_OBJECT_TYPE, LAST_UPDATED_OBJECT_ID, LAST_UPDATED_PROGRAM_ID,
    ALARM_CODE, ALARM_NAME, ALARM_NAME_KO, ALARM_NAME_EN, ALARM_DESCRIPTION,
    ALARM_CATEGORY, RECIPIENT_SCOPE, ACKNOWLEDGEMENT_SCOPE,
    SAVE_STATUS, RECEIVE_STATUS, PUSH_STATUS, EMAIL_STATUS, TEAMS_STATUS
)
SELECT d.CREATED_OBJECT_TYPE, d.CREATED_OBJECT_ID, d.CREATED_PROGRAM_ID,
       d.LAST_UPDATED_OBJECT_TYPE, d.LAST_UPDATED_OBJECT_ID, d.LAST_UPDATED_PROGRAM_ID,
       d.CODE_VALUE, d.CODE_VALUE_NAME, d.CODE_VALUE_NAME_KO, d.CODE_VALUE_NAME_EN,
       d.CODE_VALUE_DESCRIPTION, d.ALARM_CATEGORY, d.RECIPIENT_SCOPE,
       d.ACKNOWLEDGEMENT_SCOPE, d.DEFAULT_SAVE_STATUS, d.DEFAULT_RECEIVE_STATUS,
       d.DEFAULT_PUSH_STATUS, d.DEFAULT_EMAIL_STATUS, d.DEFAULT_TEAMS_STATUS
FROM TB_M26_CODE_DETAIL d
JOIN TB_M26_CODE c ON c.CODE_ID = d.CODE_ID
WHERE UPPER(c.CODE_NAME) = 'ALARM_TYPE'
  AND NOT EXISTS (
      SELECT 1 FROM TB_M26_ALARM_RULE r WHERE UPPER(r.ALARM_CODE) = UPPER(d.CODE_VALUE)
  );

