CREATE TABLE IF NOT EXISTS TB_M26_ALARM_RULE_USER (
    CREATED_OBJECT_TYPE VARCHAR(1) DEFAULT NULL COMMENT '생성Object유형',
    CREATED_OBJECT_ID VARCHAR(22) DEFAULT NULL COMMENT '생성ObjectID',
    CREATED_PROGRAM_ID VARCHAR(22) DEFAULT NULL COMMENT '생성프로그램ID',
    CREATED_TIMESTAMP DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '생성일시',
    LAST_UPDATED_OBJECT_TYPE VARCHAR(1) DEFAULT NULL COMMENT '최종변경Object유형',
    LAST_UPDATED_OBJECT_ID VARCHAR(22) DEFAULT NULL COMMENT '최종변경ObjectID',
    LAST_UPDATED_PROGRAM_ID VARCHAR(22) DEFAULT NULL COMMENT '최종변경프로그램ID',
    LAST_UPDATED_TIMESTAMP DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '최종변경일시',
    DATA_END_STATUS VARCHAR(1) DEFAULT 'N' COMMENT '데이터종료여부',
    DATA_END_OBJECT_TYPE VARCHAR(1) DEFAULT NULL COMMENT '데이터종료Object유형',
    DATA_END_OBJECT_ID VARCHAR(22) DEFAULT NULL COMMENT '데이터종료ObjectID',
    DATA_END_PROGRAM_ID VARCHAR(22) DEFAULT NULL COMMENT '데이터종료프로그램ID',
    DATA_END_TIMESTAMP DATETIME DEFAULT NULL COMMENT '데이터종료일시',
    ALARM_RULE_USER_ID BIGINT NOT NULL AUTO_INCREMENT COMMENT '알람 기준 사용자 ID',
    ALARM_RULE_ID BIGINT NOT NULL COMMENT '알람 기준 ID',
    USER_ID INT(15) UNSIGNED NOT NULL COMMENT '사용자 ID',
    RECEIVER_STATUS VARCHAR(1) NOT NULL DEFAULT 'Y' COMMENT '수신 여부',
    PUSH_ENABLED VARCHAR(1) NOT NULL DEFAULT 'Y' COMMENT '앱 알람 수신 여부',
    EMAIL_ENABLED VARCHAR(1) NOT NULL DEFAULT 'N' COMMENT '메일 수신 여부',
    TEAMS_ENABLED VARCHAR(1) NOT NULL DEFAULT 'N' COMMENT '팀즈 알림봇 수신 여부',
    PRIMARY KEY (ALARM_RULE_USER_ID),
    UNIQUE KEY UK_M26_ALARM_RULE_USER (ALARM_RULE_ID, USER_ID),
    KEY IX_M26_ALARM_RULE_USER_USER (USER_ID),
    CONSTRAINT FK_M26_ALARM_RULE_USER_RULE FOREIGN KEY (ALARM_RULE_ID) REFERENCES TB_M26_ALARM_RULE (ALARM_RULE_ID),
    CONSTRAINT FK_M26_ALARM_RULE_USER_USER FOREIGN KEY (USER_ID) REFERENCES TB_M26_USER (USER_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='알람 기준별 수신자 및 채널 설정';

INSERT INTO TB_M26_ALARM_RULE_USER (
    CREATED_OBJECT_TYPE, CREATED_OBJECT_ID, CREATED_PROGRAM_ID,
    ALARM_RULE_ID, USER_ID, RECEIVER_STATUS, PUSH_ENABLED, EMAIL_ENABLED, TEAMS_ENABLED
)
SELECT p.CREATED_OBJECT_TYPE, p.CREATED_OBJECT_ID, p.CREATED_PROGRAM_ID,
       r.ALARM_RULE_ID, p.USER_ID, p.RECEIVER_STATUS, p.PUSH_ENABLED, p.EMAIL_ENABLED, p.TEAMS_ENABLED
FROM TB_M26_USER_ALERT_PREF p
JOIN TB_M26_ALARM_RULE r ON UPPER(r.ALARM_CODE) = UPPER(p.ALARM_TYPE_CODE)
WHERE p.ALARM_TYPE_CODE <> '*'
  AND NOT EXISTS (
      SELECT 1 FROM TB_M26_ALARM_RULE_USER ru
      WHERE ru.ALARM_RULE_ID = r.ALARM_RULE_ID AND ru.USER_ID = p.USER_ID
  );
