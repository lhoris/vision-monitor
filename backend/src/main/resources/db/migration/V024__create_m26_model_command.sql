CREATE TABLE IF NOT EXISTS TB_M26_MODEL_COMMAND (
    CREATED_OBJECT_TYPE VARCHAR(1) DEFAULT NULL,
    CREATED_OBJECT_ID VARCHAR(22) DEFAULT NULL,
    CREATED_PROGRAM_ID VARCHAR(22) DEFAULT NULL,
    CREATED_TIMESTAMP DATETIME DEFAULT CURRENT_TIMESTAMP(),
    LAST_UPDATED_OBJECT_TYPE VARCHAR(1) DEFAULT NULL,
    LAST_UPDATED_OBJECT_ID VARCHAR(22) DEFAULT NULL,
    LAST_UPDATED_PROGRAM_ID VARCHAR(22) DEFAULT NULL,
    LAST_UPDATED_TIMESTAMP DATETIME DEFAULT CURRENT_TIMESTAMP() ON UPDATE CURRENT_TIMESTAMP(),
    DATA_END_STATUS VARCHAR(1) DEFAULT 'N',
    DATA_END_OBJECT_TYPE VARCHAR(1) DEFAULT NULL,
    DATA_END_OBJECT_ID VARCHAR(22) DEFAULT NULL,
    DATA_END_PROGRAM_ID VARCHAR(22) DEFAULT NULL,
    DATA_END_TIMESTAMP DATETIME DEFAULT NULL,
    MODEL_COMMAND_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    MODEL_PROCESS_ID BIGINT UNSIGNED NOT NULL,
    TARGET_SERVER_IP VARCHAR(45) NOT NULL,
    COMMAND_TYPE VARCHAR(20) NOT NULL,
    COMMAND_STATUS VARCHAR(20) NOT NULL DEFAULT 'REQUESTED',
    REQUESTED_BY VARCHAR(100) NOT NULL,
    REQUESTED_TIMESTAMP DATETIME DEFAULT CURRENT_TIMESTAMP(),
    CLAIMED_TIMESTAMP DATETIME DEFAULT NULL,
    PROCESSED_TIMESTAMP DATETIME DEFAULT NULL,
    AGENT_ID VARCHAR(100) DEFAULT NULL,
    RESULT_CODE VARCHAR(50) DEFAULT NULL,
    RESULT_MESSAGE VARCHAR(2000) DEFAULT NULL,
    RETRY_COUNT INT NOT NULL DEFAULT 0,
    PRIMARY KEY (MODEL_COMMAND_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
