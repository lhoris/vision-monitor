CREATE TABLE IF NOT EXISTS TB_M26_ALARM_LOG (
    CREATED_OBJECT_TYPE VARCHAR(1) DEFAULT NULL,
    CREATED_OBJECT_ID VARCHAR(22) DEFAULT NULL,
    CREATED_PROGRAM_ID VARCHAR(22) DEFAULT NULL,
    CREATED_TIMESTAMP DATETIME DEFAULT CURRENT_TIMESTAMP,
    LAST_UPDATED_OBJECT_TYPE VARCHAR(1) DEFAULT NULL,
    LAST_UPDATED_OBJECT_ID VARCHAR(22) DEFAULT NULL,
    LAST_UPDATED_PROGRAM_ID VARCHAR(22) DEFAULT NULL,
    LAST_UPDATED_TIMESTAMP DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    DATA_END_STATUS VARCHAR(1) DEFAULT 'N',
    DATA_END_OBJECT_TYPE VARCHAR(1) DEFAULT NULL,
    DATA_END_OBJECT_ID VARCHAR(22) DEFAULT NULL,
    DATA_END_PROGRAM_ID VARCHAR(22) DEFAULT NULL,
    DATA_END_TIMESTAMP DATETIME DEFAULT NULL,
    ALARM_LOG_ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    ALARM_TYPE VARCHAR(50) NOT NULL,
    ALARM_SEVERITY VARCHAR(20) NOT NULL,
    ALARM_MESSAGE VARCHAR(2000) NOT NULL,
    ALARM_SOURCE_TYPE VARCHAR(50) DEFAULT NULL,
    ALARM_SOURCE_ID VARCHAR(100) DEFAULT NULL,
    OCCURRED_TIMESTAMP DATETIME NOT NULL,
    TARGET_USER_ID BIGINT UNSIGNED NOT NULL,
    ACKNOWLEDGED_STATUS VARCHAR(1) DEFAULT 'N',
    ACKNOWLEDGED_TIMESTAMP DATETIME DEFAULT NULL,
    ACKNOWLEDGED_BY BIGINT UNSIGNED DEFAULT NULL,
    ALARM_CONTEXT TEXT DEFAULT NULL,
    PRIMARY KEY (ALARM_LOG_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='사용자별 알람 이력';
