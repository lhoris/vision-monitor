INSERT INTO TB_M26_ALARM_RULE_USER (
    CREATED_OBJECT_TYPE, CREATED_OBJECT_ID, CREATED_PROGRAM_ID,
    ALARM_RULE_ID, USER_ID, RECEIVER_STATUS, PUSH_ENABLED, EMAIL_ENABLED, TEAMS_ENABLED
)
SELECT 'S', 'SYSTEM', 'V045_SEED', r.ALARM_RULE_ID, u.USER_ID, 'Y', 'Y', 'N', 'N'
FROM TB_M26_ALARM_RULE r
JOIN TB_M26_USER_AUTH ua ON ua.DATA_END_STATUS = 'N'
JOIN TB_M26_AUTH a ON a.AUTH_ID = ua.AUTH_ID
JOIN TB_M26_USER u ON u.USER_ID = ua.USER_ID
WHERE UPPER(r.ALARM_CODE) = 'USER_SIGNUP_REQUEST'
  AND r.DATA_END_STATUS = 'N'
  AND u.DATA_END_STATUS = 'N'
  AND COALESCE(u.ACCOUNT_STATUS, 'active') = 'active'
  AND a.DATA_END_STATUS = 'N'
  AND UPPER(a.AUTH_CODE) = 'ADMIN'
  AND NOT EXISTS (
      SELECT 1
      FROM TB_M26_ALARM_RULE_USER existing
      WHERE existing.ALARM_RULE_ID = r.ALARM_RULE_ID
        AND existing.USER_ID = u.USER_ID
  );
