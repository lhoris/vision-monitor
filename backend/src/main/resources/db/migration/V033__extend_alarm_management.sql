ALTER TABLE TB_M26_CODE_DETAIL
    ADD COLUMN ALARM_CATEGORY VARCHAR(20) DEFAULT NULL COMMENT '알람 대분류',
    ADD COLUMN DEFAULT_SAVE_STATUS VARCHAR(1) NOT NULL DEFAULT 'Y' COMMENT '기본 로그 저장 여부',
    ADD COLUMN DEFAULT_RECEIVE_STATUS VARCHAR(1) NOT NULL DEFAULT 'Y' COMMENT '기본 수신 여부',
    ADD COLUMN RECIPIENT_SCOPE VARCHAR(20) NOT NULL DEFAULT 'ALL_ADMIN' COMMENT '수신자 범위',
    ADD COLUMN DEFAULT_PUSH_STATUS VARCHAR(1) NOT NULL DEFAULT 'Y' COMMENT '기본 push 수신 여부',
    ADD COLUMN DEFAULT_EMAIL_STATUS VARCHAR(1) NOT NULL DEFAULT 'N' COMMENT '기본 메일 수신 여부',
    ADD COLUMN DEFAULT_TEAMS_STATUS VARCHAR(1) NOT NULL DEFAULT 'N' COMMENT '기본 Teams 수신 여부',
    ADD COLUMN ACKNOWLEDGEMENT_SCOPE VARCHAR(20) NOT NULL DEFAULT 'INDIVIDUAL' COMMENT '알람 확인 범위';

ALTER TABLE TB_M26_USER_ALERT_PREF
    ADD COLUMN ALARM_TYPE_CODE VARCHAR(50) NOT NULL DEFAULT '*' COMMENT '알람 유형 코드',
    ADD COLUMN RECEIVER_STATUS VARCHAR(1) NOT NULL DEFAULT 'Y' COMMENT '알람 수신자 여부',
    ADD COLUMN PUSH_ENABLED VARCHAR(1) NOT NULL DEFAULT 'Y' COMMENT 'push 수신 여부',
    ADD COLUMN TEAMS_ENABLED VARCHAR(1) NOT NULL DEFAULT 'N' COMMENT 'Teams 수신 여부';

ALTER TABLE TB_M26_ALARM_LOG
    ADD COLUMN ALARM_GROUP_ID VARCHAR(100) DEFAULT NULL COMMENT '공동 확인 알람 그룹 ID';

INSERT INTO TB_M26_CODE (CODE_NAME, CODE_DESCRIPTION, CODE_TYPE, REMARKS)
SELECT 'ALARM_TYPE', '알람 유형', 'ALARM', '일반 알람과 모델 알람의 상세 유형'
WHERE NOT EXISTS (SELECT 1 FROM TB_M26_CODE WHERE CODE_NAME = 'ALARM_TYPE');

INSERT INTO TB_M26_CODE_DETAIL (CODE_ID, CODE_VALUE, CODE_VALUE_NAME, CODE_VALUE_NAME_KO, CODE_VALUE_NAME_EN, CODE_VALUE_DESCRIPTION, SORT_ORDER, DEFAULT_VALUE, ALARM_CATEGORY, DEFAULT_SAVE_STATUS, DEFAULT_RECEIVE_STATUS, RECIPIENT_SCOPE, DEFAULT_PUSH_STATUS, DEFAULT_EMAIL_STATUS, DEFAULT_TEAMS_STATUS, ACKNOWLEDGEMENT_SCOPE)
SELECT c.CODE_ID, 'USER_SIGNUP_REQUEST', '신규 회원가입 요청', '신규 회원가입 요청', 'New signup request', '신규 사용자 가입 신청 알람', 1, 'Y', 'GENERAL', 'Y', 'Y', 'ALL_ADMIN', 'Y', 'N', 'N', 'GROUP'
FROM TB_M26_CODE c
WHERE c.CODE_NAME = 'ALARM_TYPE'
  AND NOT EXISTS (SELECT 1 FROM TB_M26_CODE_DETAIL d WHERE d.CODE_ID = c.CODE_ID AND d.CODE_VALUE = 'USER_SIGNUP_REQUEST');
