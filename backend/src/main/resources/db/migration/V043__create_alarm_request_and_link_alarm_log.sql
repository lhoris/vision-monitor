CREATE TABLE IF NOT EXISTS TB_M26_ALARM_REQ (
    CREATED_OBJECT_TYPE VARCHAR(1) DEFAULT NULL COMMENT '생성Object유형',
    CREATED_OBJECT_ID VARCHAR(22) DEFAULT NULL COMMENT '생성ObjectID',
    CREATED_PROGRAM_ID VARCHAR(22) DEFAULT NULL COMMENT '생성프로그램ID',
    CREATED_TIMESTAMP DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '생성일시',
    LAST_UPDATED_OBJECT_TYPE VARCHAR(1) DEFAULT NULL COMMENT '최종변경Object유형',
    LAST_UPDATED_OBJECT_ID VARCHAR(22) DEFAULT NULL COMMENT '최종변경ObjectID',
    LAST_UPDATED_PROGRAM_ID VARCHAR(22) DEFAULT NULL COMMENT '최종변경프로그램ID',
    LAST_UPDATED_TIMESTAMP DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '최종변경일시',
    DATA_END_STATUS VARCHAR(1) DEFAULT 'N' COMMENT '데이터종료여부',
    DATA_END_OBJECT_TYPE VARCHAR(1) DEFAULT NULL COMMENT '데이터종료Object유형',
    DATA_END_OBJECT_ID VARCHAR(22) DEFAULT NULL COMMENT '데이터종료ObjectID',
    DATA_END_PROGRAM_ID VARCHAR(22) DEFAULT NULL COMMENT '데이터종료프로그램ID',
    DATA_END_TIMESTAMP DATETIME DEFAULT NULL COMMENT '데이터종료일시',
    ALARM_REQ_ID BIGINT NOT NULL AUTO_INCREMENT COMMENT '알람 요청 ID',
    ALARM_RULE_ID BIGINT NOT NULL COMMENT '알람 기준 ID',
    ALARM_CODE VARCHAR(50) NOT NULL COMMENT '알람 코드',
    ALARM_SEVERITY VARCHAR(20) NOT NULL COMMENT '알람 심각도',
    ALARM_MESSAGE VARCHAR(2000) NOT NULL COMMENT '알람 메시지',
    ALARM_SOURCE_TYPE VARCHAR(50) DEFAULT NULL COMMENT '알람 발생 유형',
    ALARM_SOURCE_ID VARCHAR(100) DEFAULT NULL COMMENT '알람 발생 ID',
    SOURCE_EVENT_ID VARCHAR(100) NOT NULL COMMENT '원천 이벤트 ID',
    ALARM_GROUP_ID VARCHAR(100) DEFAULT NULL COMMENT '알람 그룹 ID',
    OCCURRED_TIMESTAMP DATETIME NOT NULL COMMENT '발생일시',
    ALARM_CONTEXT TEXT DEFAULT NULL COMMENT '알람 문맥',
    PRIMARY KEY (ALARM_REQ_ID),
    UNIQUE KEY UK_M26_ALARM_REQ_SOURCE_EVENT (SOURCE_EVENT_ID),
    KEY IX_M26_ALARM_REQ_RULE (ALARM_RULE_ID),
    CONSTRAINT FK_M26_ALARM_REQ_RULE FOREIGN KEY (ALARM_RULE_ID) REFERENCES TB_M26_ALARM_RULE (ALARM_RULE_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='알람 요청 원장';

ALTER TABLE TB_M26_ALARM_LOG
    ADD COLUMN ALARM_REQ_ID BIGINT DEFAULT NULL COMMENT '알람 요청 ID',
    ADD KEY IX_M26_ALARM_LOG_REQ (ALARM_REQ_ID),
    ADD UNIQUE KEY UK_M26_ALARM_LOG_REQ_TARGET (ALARM_REQ_ID, TARGET_USER_ID),
    ADD CONSTRAINT FK_M26_ALARM_LOG_REQ FOREIGN KEY (ALARM_REQ_ID) REFERENCES TB_M26_ALARM_REQ (ALARM_REQ_ID);
