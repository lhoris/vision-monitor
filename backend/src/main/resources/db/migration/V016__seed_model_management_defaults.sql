    CREATED_OBJECT_TYPE, CREATED_OBJECT_ID, CREATED_PROGRAM_ID,
    LAST_UPDATED_OBJECT_TYPE, LAST_UPDATED_OBJECT_ID, LAST_UPDATED_PROGRAM_ID,
    CODE_ID, CODE_VALUE, CODE_VALUE_NAME, CODE_VALUE_NAME_KO, CODE_VALUE_NAME_EN,
    CODE_VALUE_DESCRIPTION, SORT_ORDER, DEFAULT_VALUE, DATA_END_STATUS
)
SELECT 'S', 'SYSTEM', 'V016_SEED', 'S', 'SYSTEM', 'V016_SEED',
       c.CODE_ID, seed.CODE_VALUE, seed.CODE_VALUE_NAME_KO, seed.CODE_VALUE_NAME_KO,
       seed.CODE_VALUE_NAME_EN, seed.CODE_VALUE_DESCRIPTION, seed.SORT_ORDER, NULL, 'N'
FROM TB_M26_CODE c
JOIN (
    SELECT 'HEATING' CODE_VALUE, '가열' CODE_VALUE_NAME_KO, 'Heating' CODE_VALUE_NAME_EN, 'Heating process' CODE_VALUE_DESCRIPTION, 10 SORT_ORDER
