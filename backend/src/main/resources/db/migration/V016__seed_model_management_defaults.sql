WHERE UPPER(c.CODE_NAME) = 'PROCESS_AREA'
  AND NOT EXISTS (SELECT 1 FROM TB_M26_CODE_DETAIL d WHERE d.CODE_ID = c.CODE_ID AND UPPER(d.CODE_VALUE) = seed.CODE_VALUE);

