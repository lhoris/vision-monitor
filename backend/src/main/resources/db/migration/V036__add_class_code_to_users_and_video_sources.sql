ALTER TABLE TB_M26_USER
    ADD COLUMN CLASS_CODE VARCHAR(30) NOT NULL DEFAULT 'COMMON' AFTER USER_POSITION;

ALTER TABLE TB_M26_VIDEO_SOURCE
    ADD COLUMN CLASS_CODE VARCHAR(30) NOT NULL DEFAULT 'COMMON' AFTER MODEL_PROCESS_ID;

UPDATE TB_M26_USER
SET CLASS_CODE = 'COMMON'
WHERE CLASS_CODE IS NULL OR CLASS_CODE = '';

UPDATE TB_M26_VIDEO_SOURCE
SET CLASS_CODE = 'COMMON'
WHERE CLASS_CODE IS NULL OR CLASS_CODE = '';

INSERT INTO TB_M26_CODE (
    CODE_NAME, CODE_DESCRIPTION, CODE_TYPE, REMARKS, DATA_END_STATUS
)
SELECT 'USER_CLASS', '사용자 반', 'SYSTEM', '사용자와 영상의 반 분류', 'N'
WHERE NOT EXISTS (
    SELECT 1 FROM TB_M26_CODE WHERE UPPER(CODE_NAME) = 'USER_CLASS'
);

INSERT INTO TB_M26_CODE_DETAIL (
    CODE_ID, CODE_VALUE, CODE_VALUE_NAME, CODE_VALUE_NAME_KO, CODE_VALUE_NAME_EN,
    CODE_VALUE_DESCRIPTION, SORT_ORDER, DEFAULT_VALUE, REMARKS, DATA_END_STATUS
)
SELECT code.CODE_ID, class_code.CODE_VALUE, class_code.CODE_VALUE_NAME,
       class_code.CODE_VALUE_NAME_KO, class_code.CODE_VALUE_NAME_EN,
       class_code.CODE_VALUE_DESCRIPTION, class_code.SORT_ORDER,
       class_code.DEFAULT_VALUE, class_code.REMARKS, 'N'
FROM TB_M26_CODE code
JOIN (
    SELECT 'HEATING' AS CODE_VALUE, '가열반' AS CODE_VALUE_NAME, '가열반' AS CODE_VALUE_NAME_KO,
           'Heating' AS CODE_VALUE_NAME_EN, '가열반' AS CODE_VALUE_DESCRIPTION, 10 AS SORT_ORDER,
           'N' AS DEFAULT_VALUE, '사용자 및 영상 분류' AS REMARKS
    UNION ALL SELECT 'ROLLING', '압연반', '압연반', 'Rolling', '압연반', 20, 'N', '사용자 및 영상 분류'
    UNION ALL SELECT 'COOLING', '냉각반', '냉각반', 'Cooling', '냉각반', 30, 'N', '사용자 및 영상 분류'
    UNION ALL SELECT 'TEST', '시험반', '시험반', 'Testing', '시험반', 40, 'N', '사용자 및 영상 분류'
    UNION ALL SELECT 'EQUIPMENT', '설비반', '설비반', 'Equipment', '설비반', 50, 'N', '사용자 및 영상 분류'
    UNION ALL SELECT 'COMMON', '공통', '공통', 'Common', '공통', 60, 'Y', '전체 사용자 공통 분류'
) class_code ON 1 = 1
WHERE UPPER(code.CODE_NAME) = 'USER_CLASS'
  AND NOT EXISTS (
      SELECT 1 FROM TB_M26_CODE_DETAIL detail
      WHERE detail.CODE_ID = code.CODE_ID
        AND UPPER(detail.CODE_VALUE) = class_code.CODE_VALUE
  );
