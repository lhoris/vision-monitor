-- Vision Monitor 최종 스키마
--
-- 이 파일은 Flyway 마이그레이션을 대체하는 신규 환경용 기준 DDL이다.
-- 기존 운영 데이터베이스에는 그대로 실행하지 말고, 백업 후 테이블별 차이를 검토한다.
--
-- 적용 원칙
-- 1. 감사 컬럼은 모든 테이블의 앞쪽에 둔다.
-- 2. 테이블 간 관계는 논리적으로만 관리하며 FK 제약조건을 생성하지 않는다.
-- 3. UK 및 보조 인덱스는 생성하지 않는다. 필요한 경우 운영 기준에 따라 별도 추가한다.
-- 4. Runtime Agent 전용 테이블은 제외한다. MODEL_PROCESS와 MODEL_COMMAND는
--    화면과 Agent가 함께 사용하는 공유 테이블이므로 포함한다.

-- ================================================================
-- 공통 감사 컬럼을 포함한 기준 테이블
-- ================================================================

